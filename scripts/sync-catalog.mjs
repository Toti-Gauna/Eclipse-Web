/** Run from Eclipse-Web: node scripts/sync-catalog.mjs [../Eclipse-be]. No runtime cross-repo dependency. */
import fs from 'node:fs';
import ts from 'typescript';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root = process.cwd();
const read = (name) => JSON.parse(fs.readFileSync(path.join(root, 'content', `${name}.json`), 'utf8'));
const p = read('plans'),
  i = read('items'),
  m = read('maintenance'),
  f = read('founders');
const snapshot = {
  schemaVersion: 2,
  catalogVersion: p.catalogVersion,
  categories: i.categories,
  items: i.items.map((x) => ({
    id: x.id,
    category: x.category,
    name: x.name,
    priceCents: Math.round(x.priceUsd * 100),
    campaign: !!x.campaign,
    compatiblePlans: x.compatiblePlans ?? [],
  })),
  plans: p.plans.map((x) => ({
    id: x.id,
    name: x.name,
    tier: x.tier,
    rangeCents: { from: Math.round(x.priceUsd.from * 100), to: Math.round(x.priceUsd.to * 100) },
    items: x.items,
    maintenance: x.maintenance,
    bonusItemId: x.bonus?.itemId ?? null,
    campaign: !!x.campaign,
    scope: x.includes,
  })),
  maintenance: m.plans.map((x) => ({ id: x.id, name: x.name, monthlyCents: Math.round(x.priceUsd * 100) })),
  annualMonthsCharged: m.annualMonthsCharged,
  voiceUsage: {
    id: m.voiceUsage.id,
    itemId: m.voiceUsage.whenItem,
    name: m.voiceUsage.name,
    note: m.voiceUsage.note,
    monthlyCents: Math.round(m.voiceUsage.priceUsd * 100),
  },
  goals: ['encontrar', 'atender', 'ordenar', 'vender', 'fidelizar', 'app', 'diagnostico'],
  verticals: read('verticals').verticals.map(({ id, name }) => ({ id, name })),
  founders: { total: f.total, remainingSnapshot: f.total - f.slots.filter((x) => x.filled).length, reservesSlots: false },
  offers: read('offers').offers.map((x) => {
    const { priceUsd, minSubtotalUsd, ...rest } = x;
    return {
      ...rest,
      ...(priceUsd === undefined ? {} : { priceCents: Math.round(priceUsd * 100) }),
      ...(minSubtotalUsd === undefined ? {} : { minSubtotalCents: Math.round(minSubtotalUsd * 100) }),
    };
  }),
};
const canonical = (v) =>
  v === null || typeof v !== 'object'
    ? JSON.stringify(v)
    : Array.isArray(v)
      ? `[${v.map(canonical).join(',')}]`
      : `{${Object.keys(v)
          .sort()
          .map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`)
          .join(',')}}`;
const version = `${snapshot.catalogVersion}-${createHash('sha256').update(canonical(snapshot)).digest('hex').slice(0, 16)}`;
const fixture = { ...snapshot, version, currency: 'USD', provisional: true };

const backend = path.resolve(process.argv.find((value, index) => index > 1 && !value.startsWith('--')) ?? '../Eclipse-be');
if (process.argv.includes('--check')) {
  const source = fs.readFileSync(path.join(backend, 'src/plans/catalog-data.ts'), 'utf8');
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
  const actual = (await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`)).COMMERCIAL_SNAPSHOT;
  const saved = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/backend-catalog.reto-v2.json'), 'utf8'));
  if (canonical(actual) !== canonical(snapshot) || canonical(saved) !== canonical(fixture))
    throw new Error('Catalog drift: run sync-catalog and review both repos.');
  console.log(`PASS catalog synchronization ${version}`);
  process.exit(0);
}
fs.writeFileSync(path.join(root, 'tests/fixtures/backend-catalog.reto-v2.json'), JSON.stringify(fixture, null, 2) + '\n');
fs.writeFileSync(
  path.join(backend, 'src/plans/catalog-data.ts'),
  '// Generated by Eclipse-Web/scripts/sync-catalog.mjs. USD cents; review coordinated PRs.\nexport const COMMERCIAL_SNAPSHOT = ' +
    JSON.stringify(snapshot, null, 2) +
    ' as const;\n',
);
console.log(`Catalog ${version}: synchronized backend snapshot and frontend fixture.`);
